HEADER_TEMPLATE = "{title} — 第 {page} 页 / 共 {total} 页"


def build(out_dir: Path = OUT_DIR) -> list[Path]:
    import pymupdf

    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for doc_id, spec in DOCUMENTS.items():
        pages = spec["pages"]
        doc = pymupdf.open()
        doc.set_metadata(
            {
                "title": spec["title"],
                "author": "华瑞精密制造有限公司（虚构）",
                "subject": f"Benchmark 文档 {doc_id}",
                "creationDate": "D:20250101000000Z",
                "modDate": "D:20250101000000Z",
                "producer": "aieb-benchmark",
                "creator": "aieb-benchmark",
            }
        )
        for index, body in enumerate(pages, start=1):
            page = doc.new_page(width=595, height=842)  # A4
            header = HEADER_TEMPLATE.format(
                title=spec["title"], page=index, total=len(pages)
            )
            page.insert_text((56, 50), header, fontname="china-s", fontsize=9)
            overflow = page.insert_textbox(
                pymupdf.Rect(56, 70, 539, 790),
                body.strip("\n"),
                fontname="china-s",
                fontsize=10.5,
                lineheight=1.55,
            )
            if overflow < 0:
                raise RuntimeError(
                    f"{doc_id} 第 {index} 页内容超出 A4 版面（溢出 {-overflow:.1f}pt），"
                    "请精简正文以保证页码稳定"
                )
        path = out_dir / spec["filename"]
        doc.save(str(path), deflate=True, garbage=3)
        doc.close()
        written.append(path)
    return written


def page_texts(doc_id: str) -> list[str]:
    """返回某文档逐页正文（用于数据集校验脚本）。"""
    import pymupdf

    path = OUT_DIR / DOCUMENTS[doc_id]["filename"]
    with pymupdf.open(str(path)) as doc:
        return [page.get_text("text") for page in doc]


